#!/usr/bin/env Rscript
# Records the exact R session used for the analysis.
# Run from the repository root:  Rscript scripts/session_info.R
# Writes sessionInfo.txt, which lists R, the platform, the packages the scripts
# load, and every dependency that ends up loaded with them.
#
# MRMix and RadialMR are not listed: no script calls them. Both are named in
# TwoSampleMR's DESCRIPTION Imports, so renv installs them and records them in
# renv.lock, but TwoSampleMR's namespace does not load them in this session
# (they are absent from the list below). No radial-MR or MR-Mix analysis was run.

pkgs <- c("TwoSampleMR", "MRPRESSO", "ieugwasr",
          "data.table", "dplyr", "ggplot2", "ggrepel", "scales",
          "openxlsx", "Matrix", "ragg")

for (p in pkgs) {
  suppressPackageStartupMessages(
    library(p, character.only = TRUE, quietly = TRUE, warn.conflicts = FALSE)
  )
}

si <- capture.output(sessionInfo())

hdr <- c(
  "# R session used for the analysis",
  "# Generated by scripts/session_info.R; regenerate with:",
  "#   Rscript scripts/session_info.R",
  ""
)

writeLines(c(hdr, si), "sessionInfo.txt")
message("wrote sessionInfo.txt (", length(si), " lines)")
